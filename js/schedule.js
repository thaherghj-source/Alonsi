    // تظليل وتنسيق خلايا الحصص في الجدول
    formatCell: function(val) {
        if (!val || val === "ـ" || val === "لا يوجد") {
            return `<span class="text-slate-300">-</span>`;
        }
        if (val.includes("إداري")) {
            return `<span class="px-2 py-1 bg-slate-100 text-slate-600 rounded-lg font-bold text-xs">${val}</span>`;
        }
        return `<span class="px-2.5 py-1 bg-indigo-100 text-indigo-900 rounded-lg font-bold text-xs shadow-sm">${val}</span>`;
    }
