// تنفيذ الكود تلقائياً فور فتح صفحة المعلم
document.addEventListener("DOMContentLoaded", () => {
    // 1. قراءة اسم المعلم المسجل دخوله من الـ localStorage (أو المتصفح)
    let currentTeacherName = localStorage.getItem("loggedInTeacher");

    // إذا لم يتم العثور على اسم مخزن، نأخذ اسم المعلم الظاهر في أعلى الصفحة كخيار احتياطي
    const nameDisplay = document.getElementById("teacher-name-display");
    if (!currentTeacherName && nameDisplay) {
        currentTeacherName = nameDisplay.textContent.trim();
    }

    if (nameDisplay && currentTeacherName) {
        nameDisplay.textContent = currentTeacherName;
    }

    console.log("المعلم الحالي:", currentTeacherName);

    // 2. البحث عن جدول هذا المعلم وعرضه
    const tableBody = document.getElementById("teacher-schedule-body");
    if (!tableBody) return;

    if (currentTeacherName && SCHOOL_TIMETABLE_DATA.teacherSchedules[currentTeacherName]) {
        const teacherSchedule = SCHOOL_TIMETABLE_DATA.teacherSchedules[currentTeacherName];
        renderScheduleTable(teacherSchedule);
    } else {
        // إذا كان الاسم غير موجود بالمنظومة، نعرض جدولاً فارغاً أو رسالة تنبيه
        tableBody.innerHTML = `<tr><td colspan="8" style="text-align: center; color: red;">عذراً، لم يتم العثور على جدول مسجل لهذا الاسم.</td></tr>`;
    }
});

// دالة رسم الجدول داخل HTML
function renderScheduleTable(scheduleArray) {
    const tableBody = document.getElementById("teacher-schedule-body");
    tableBody.innerHTML = ""; // تفريغ الجدول

    scheduleArray.forEach(row => {
        const tr = document.createElement("tr");
        tr.innerHTML = `
            <td><strong>${row.day}</strong></td>
            <td>${row.c1 || "ـ"}</td>
            <td>${row.c2 || "ـ"}</td>
            <td>${row.c3 || "ـ"}</td>
            <td>${row.c4 || "ـ"}</td>
            <td>${row.c5 || "ـ"}</td>
            <td>${row.c6 || "ـ"}</td>
            <td>${row.c7 || "ـ"}</td>
        `;
        tableBody.appendChild(tr);
    });
}
